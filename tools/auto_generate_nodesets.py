"""Generate Python modules with the type node identifiers of OPC UA NodeSet2 XML files.

Reads every ``*.NodeSet2.xml`` in the nodeset directory and writes one module per file plus an ``__init__.py`` with
``NODE_SETS`` next to them. Defaults to core's own nodesets; other packages pass their directory, e.g.
``python tools/auto_generate_nodesets.py ../sfkl/src/opensmi/sfkl/nodesets``.
"""

import argparse
import logging
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from pprint import pformat
from string import Template
from typing import Final

from asyncua.ua import NodeId

TOOLS_PATH: Final[Path] = Path(__file__).resolve().parent
NODESET_PATH: Final[Path] = TOOLS_PATH.parent / "src" / "opensmi" / "core" / "nodesets"
TEMPLATE: Final[Template] = Template((TOOLS_PATH / "nodeset.py.template").read_text(encoding="utf-8"))
TYPE_TAGS: Final[set[str]] = {"UAObjectType", "UADataType", "UAVariableType"}
OPC_UA_URI: Final[str] = "http://opcfoundation.org/UA/"

logging.basicConfig(level=logging.INFO)
_LOGGER = logging.getLogger(__name__)


def _snake_case(value: str) -> str:
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    return value.lower()


@dataclass
class _ModelEntry:
    uri: str
    publication_date: str
    version: str


@dataclass
class _ParsedNodeSet:
    name: str
    path: Path
    model: _ModelEntry
    required_models: list[_ModelEntry]
    entries: dict[str, int | str]


@dataclass
class _ProcessModelEntry(_ModelEntry):
    path: Path
    class_name: str


def _write(parsed: _ParsedNodeSet, out_path: Path) -> tuple[str, Path]:
    class_name = f"{parsed.name}NodeIds"
    required_uris = [model.uri for model in parsed.required_models if model.uri not in (parsed.model.uri, OPC_UA_URI)]

    identifier_source = "\n".join(
        f"    {entry} = NodeIdDefinition(identifier={parsed.entries[entry]!r}, namespace_uri=URI)"
        for entry in sorted(parsed.entries)
    )

    path = out_path / f"{_snake_case(parsed.name)}.py"
    path.write_text(
        TEMPLATE.substitute(
            generated_on=datetime.now().astimezone(),
            class_name=class_name,
            nodeset=parsed.name,
            file_name=parsed.path.name,
            uri=parsed.model.uri,
            version=parsed.model.version,
            required_uris=pformat(tuple(required_uris)),
            identifiers=identifier_source,
        ),
        encoding="utf-8",
    )

    return class_name, path


def _write__init__(files: list[_ProcessModelEntry], out_path: Path) -> None:
    path = out_path / "__init__.py"
    with path.open("w", encoding="utf-8") as file:
        file.write("# SPDX-FileCopyrightText: 2026 OpenSMI Contributors\n")
        file.write("#\n")
        file.write("# SPDX-License-Identifier: MIT\n\n")
        file.write("# !!! autogenerated code, do not change manually !!!\n")
        file.write(f"# generated on {datetime.now().astimezone()}\n\n")
        file.write('"""Autogenerated OPC UA node identifiers."""\n\n')
        file.write("from typing import Final\n\n")
        file.write("from opensmi.core.protocols import NamespaceProvider\n\n")

        for entry in files:
            file.write(f"from .{entry.path.stem} import {entry.class_name} as {entry.class_name}\n")

        file.write("\n\n")
        file.write("NODE_SETS: Final[dict[str, type[NamespaceProvider]]] = {\n")
        for entry in files:
            file.write(f'    "{entry.uri}": {entry.class_name},\n')
        file.write("}\n")

    _check(path)


def _check(path: Path) -> None:
    subprocess.run([sys.executable, "-m", "ruff", "check", "--fix", str(path)], check=True)
    subprocess.run([sys.executable, "-m", "ruff", "format", str(path)], check=True)

    # finally, make sure the file is valid python after formatting & linting
    compile(path.read_text(encoding="utf-8"), path, "exec")


def _process_model(node: ET.Element) -> _ModelEntry:
    model_uri = node.attrib.get("ModelUri")
    assert model_uri

    return _ModelEntry(
        uri=model_uri,
        publication_date=node.attrib.get("PublicationDate", "??"),
        version=node.attrib.get("Version", "??"),
    )


def _process_models(node: ET.Element) -> tuple[_ModelEntry, list[_ModelEntry]]:
    model = _process_model(node)
    required_models = [_process_model(child) for child in node.iter()]
    return model, required_models


def _parse_nodeset_xml(path: Path) -> _ParsedNodeSet:
    _LOGGER.info("Processing '%s'...", path)
    entries: dict[str, int | str] = {}

    tree = ET.parse(path)
    root = tree.getroot()

    uri, required_models = None, None
    for node in root.iter():  # Iterate through all UAObjectType nodes
        local_name = node.tag.rsplit("}", 1)[-1]  # without xml namespace

        if local_name == "Model":
            # TODO(CaHa): what about multiple "model" tags?
            uri, required_models = _process_models(node)
            continue
        if local_name not in TYPE_TAGS:
            continue
        try:
            bname = node.attrib.get("BrowseName")
            assert bname
            name = bname.split(":")[-1]
            raw_node_id = node.attrib.get("NodeId")
            assert raw_node_id
            node_id = NodeId.from_string(raw_node_id)

            if name in entries:
                _LOGGER.warning("'%s' already used, skipping!", name)
                continue
            if not isinstance(node_id.Identifier, int | str):
                _LOGGER.warning("'%s' has a GUID or opaque identifier, skipping!", name)
                continue
            entries[name] = node_id.Identifier
        except (ValueError, AttributeError):
            _LOGGER.warning("Could not process %s, skipping!", node)

    if uri is None:
        _LOGGER.error("No URI found in %s, aborting!", path)
        sys.exit(1)

    # fail if these don't exist
    assert required_models

    return _ParsedNodeSet(
        name="".join(path.stem.split(".")[2:-1]),
        path=path,
        model=uri,
        required_models=required_models,
        entries=entries,
    )


def main() -> None:  # noqa: D103
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "path", nargs="?", type=Path, default=NODESET_PATH, help="directory with the *.NodeSet2.xml files"
    )
    out_path: Path = parser.parse_args().path.resolve()

    files = []
    for src_path in sorted(out_path.glob("*.NodeSet2.xml")):
        parsed = _parse_nodeset_xml(src_path)
        class_name, dest_path = _write(parsed, out_path)
        files.append(
            _ProcessModelEntry(
                uri=parsed.model.uri,
                publication_date=parsed.model.publication_date,
                version=parsed.model.version,
                path=dest_path,
                class_name=class_name,
            )
        )

        # format and lint generated file, check for errors
        _check(dest_path)

    _write__init__(files, out_path)


if __name__ == "__main__":
    main()
